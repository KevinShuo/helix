//! Deterministic paths and CMake integration. Models never choose output paths.
use anyhow::{ensure, Context, Result};
use helix_view::{
    ai_doc::Target,
    ai_test::{AiTestConfig, FileChange, Project, Snapshot},
};
use std::path::{Path, PathBuf};

const MARKER: &str = "# Generated by Helix AI tests; review assertions before relying on them.";
const C_MARKER: &str = "// Generated by Helix AI tests; review assertions before relying on them.";

pub(crate) fn snapshot(path: &Path) -> Result<Snapshot> {
    let text = match std::fs::read(path) {
        Ok(bytes) => {
            ensure!(bytes.len() <= 262_144, "上下文文件过大：{}", path.display());
            Some(String::from_utf8(bytes).context("上下文文件不是 UTF-8")?)
        }
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => None,
        Err(e) => return Err(e.into()),
    };
    Ok(Snapshot {
        path: path.to_owned(),
        text,
    })
}

pub(crate) fn confined(root: &Path, path: &Path) -> Result<PathBuf> {
    let path = if path.is_absolute() {
        path.to_owned()
    } else {
        root.join(path)
    };
    ensure!(
        !path
            .components()
            .any(|c| matches!(c, std::path::Component::ParentDir)),
        "路径不能含 .."
    );
    let mut ancestor = path.as_path();
    while std::fs::symlink_metadata(ancestor).is_err() {
        ancestor = ancestor.parent().context("路径没有有效父目录")?;
    }
    ensure!(
        helix_stdx::path::canonicalize(ancestor.canonicalize()?).starts_with(root),
        "路径超出项目：{}",
        path.display()
    );
    for entry in path.ancestors().take_while(|p| *p != root) {
        if let Ok(meta) = std::fs::symlink_metadata(entry) {
            ensure!(
                !meta.file_type().is_symlink(),
                "不自动修改或读取符号链接路径：{}",
                entry.display()
            );
        }
    }
    Ok(path)
}

pub(crate) fn root_for(source: &Path, language: &str) -> PathBuf {
    let parent = source.parent().unwrap();
    let mut cmake_root = None;
    for dir in parent.ancestors() {
        if language == "python"
            && ["pyproject.toml", "pytest.ini", "setup.cfg", "setup.py"]
                .iter()
                .any(|n| dir.join(n).is_file())
        {
            return dir.to_owned();
        }
        if language != "python" && dir.join("CMakeLists.txt").is_file() {
            cmake_root = Some(dir.to_owned());
            if std::fs::read_to_string(dir.join("CMakeLists.txt"))
                .ok()
                .and_then(|s| commands(&s).ok())
                .is_some_and(|calls| calls.iter().any(|(c, _)| c == "project"))
            {
                return dir.to_owned();
            }
        }
        if dir.join(".git").exists() {
            return cmake_root.unwrap_or_else(|| dir.to_owned());
        }
    }
    cmake_root.unwrap_or_else(|| parent.to_owned())
}

fn add_context(project: &mut Project, path: &Path) -> Result<()> {
    let path = confined(&project.root, path)?;
    if project.snapshots.iter().any(|s| s.path == path) {
        return Ok(());
    }
    let snap = snapshot(&path)?;
    if let Some(text) = &snap.text {
        if project.context.len() + text.len() < 32_768 {
            project.context.push_str(&format!(
                "\n<FILE path={:?}>\n{text}\n</FILE>\n",
                path.strip_prefix(&project.root)?
            ));
        }
    }
    project.snapshots.push(snap);
    Ok(())
}

fn change(project: &mut Project, path: PathBuf, after: String) -> Result<()> {
    let path = confined(&project.root, &path)?;
    let before = snapshot(&path)?;
    if !project.snapshots.iter().any(|s| s.path == path) {
        project.snapshots.push(before.clone());
    }
    if before.text.as_deref() != Some(after.as_str()) {
        project.build_changes.push(FileChange { before, after });
    }
    Ok(())
}

fn append(project: &mut Project, path: PathBuf, text: &str, sentinel: &str) -> Result<()> {
    let before = snapshot(&path)?;
    if !project.snapshots.iter().any(|s| s.path == path) {
        project.snapshots.push(before.clone());
    }
    let mut after = before.text.unwrap_or_default();
    if after.contains(sentinel) {
        return Ok(());
    }
    if !after.ends_with('\n') && !after.is_empty() {
        after.push('\n');
    }
    after.push_str(text);
    change(project, path, after)
}

pub(crate) fn discover(source: &Path, target: &Target, config: &AiTestConfig) -> Result<Project> {
    let source =
        helix_stdx::path::canonicalize(source.canonicalize().context("请先保存被测源文件")?);
    let root = helix_stdx::path::canonicalize(root_for(&source, &target.language).canonicalize()?);
    let signature = if target.language == "python" {
        let line = target
            .source
            .lines()
            .find(|l| {
                l.trim_start().starts_with("def ") || l.trim_start().starts_with("async def ")
            })
            .unwrap_or(&target.name);
        line.get(..line.rfind(')').map_or(line.len(), |n| n + 1))
            .unwrap_or(line)
    } else {
        target.source.split('{').next().unwrap_or(&target.name)
    };
    let scope = target
        .supporting
        .lines()
        .filter(|s| {
            ["class ", "struct ", "namespace "]
                .iter()
                .any(|p| s.trim_start().starts_with(p))
        })
        .collect::<Vec<_>>()
        .join(" ");
    let identity = format!(
        "{}:{scope}:{}",
        source.strip_prefix(&root)?.display(),
        signature.split_whitespace().collect::<Vec<_>>().join(" ")
    );
    let hash = identity.bytes().fold(0xcbf29ce484222325u64, |h, b| {
        (h ^ b as u64).wrapping_mul(0x100000001b3)
    });
    let slug: String = target
        .name
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() {
                c.to_ascii_lowercase()
            } else {
                '_'
            }
        })
        .take(48)
        .collect();
    let id = format!("{slug}_{hash:016x}");
    let suite = format!("HelixAi{hash:016X}");
    let test_file = if target.language == "python" {
        root.join("tests").join(format!("test_helix_{id}.py"))
    } else {
        root.join("tests/helix-ai")
            .join(&id)
            .join(format!("{slug}_test.cpp"))
    };
    let mut project = Project {
        root: root.clone(),
        source: source.clone(),
        test_file: confined(&root, &test_file)?,
        language: target.language.clone(),
        target_name: format!("helix_ai_{id}"),
        test_filter: suite,
        context: String::new(),
        snapshots: Vec::new(),
        build_changes: Vec::new(),
        notes: Vec::new(),
    };
    add_context(&mut project, &source)?;
    for name in [
        "pyproject.toml",
        "pytest.ini",
        "setup.cfg",
        "conftest.py",
        "CMakePresets.json",
        "CMakeUserPresets.json",
    ] {
        add_context(&mut project, &root.join(name))?;
    }
    let old = snapshot(&project.test_file)?;
    if let Some(text) = &old.text {
        ensure!(
            text.starts_with(MARKER) || text.starts_with(C_MARKER),
            "测试文件已存在且不属于自动生成文件：{}",
            project.test_file.display()
        );
        project
            .notes
            .push("重新生成将替换此前生成的同一函数测试；请检查 diff。".into());
    }
    project.snapshots.push(old);
    for dir in [
        source.parent().unwrap().to_owned(),
        root.join("include"),
        root.join("tests"),
    ] {
        if !dir.is_dir() {
            continue;
        }
        let mut paths = std::fs::read_dir(&dir)?
            .filter_map(|e| e.ok().map(|e| e.path()))
            .collect::<Vec<_>>();
        paths.sort();
        for path in paths.into_iter().filter(|p| p.is_file()).take(32) {
            let ext = path.extension().and_then(|s| s.to_str()).unwrap_or("");
            let name = path.file_name().unwrap().to_string_lossy();
            if matches!(ext, "h" | "hpp" | "hxx")
                || (target.language == "python"
                    && (name == "conftest.py" || name.starts_with("test_"))
                    && path != project.test_file)
            {
                add_context(&mut project, &path)?;
            }
        }
    }
    if target.language != "python" {
        cmake(&mut project, target, config)?;
    }
    Ok(project)
}

fn cmake_path(path: &Path) -> String {
    path.to_string_lossy()
        .replace('\\', "/")
        .replace('"', "\\\"")
        .replace('$', "\\$")
        .replace(';', "\\;")
}

fn cmake(project: &mut Project, target: &Target, config: &AiTestConfig) -> Result<()> {
    ensure!(
        !target.source.trim_start().starts_with("static ")
            || target.supporting.contains("class ")
            || target.supporting.contains("struct "),
        "首版不支持独立测试文件调用 static 内部函数"
    );
    ensure!(
        !target
            .supporting
            .lines()
            .any(|l| l.trim() == "namespace" || l.trim() == "namespace {"),
        "首版不支持匿名 namespace 内部函数"
    );
    let root_file = project.root.join("CMakeLists.txt");
    if !root_file.is_file() {
        project.target_name.clear();
        project
            .notes
            .push("未发现 CMakeLists.txt：仅生成测试草稿；需接入项目构建后运行。".into());
        return Ok(());
    }
    let mut files = Vec::new();
    collect_cmake(&project.root, &project.root, &mut files)?;
    let mut declarations = Vec::new();
    let mut calls = Vec::new();
    for (path, source_dir) in files {
        add_context(project, &path)?;
        let source = std::fs::read_to_string(&path)?;
        for (cmd, args) in discovery_commands(&source)? {
            let args = args
                .into_iter()
                .map(|arg| expand_cmake_path(&arg, &path, &source_dir, &project.root))
                .collect::<Vec<_>>();
            if matches!(cmd.as_str(), "add_library" | "add_executable") && !args.is_empty() {
                declarations.push((
                    args[0].clone(),
                    cmd == "add_library",
                    source_dir.clone(),
                    args.clone(),
                ));
            }
            calls.push((cmd, args, source_dir.clone()));
        }
    }
    let test_target = config.test_target.clone().or_else(|| {
        let candidates = calls
            .iter()
            .filter(|(c, a, _)| {
                c == "target_link_libraries"
                    && a.iter()
                        .any(|s| s.starts_with("GTest::") || s == "gtest_main")
            })
            .filter_map(|(_, a, _)| a.first().cloned())
            .collect::<std::collections::BTreeSet<_>>();
        (candidates.len() == 1).then(|| candidates.into_iter().next().unwrap())
    });
    if let Some(name) = &test_target {
        ensure!(
            valid_target(name)
                && !declarations.iter().any(|(n, lib, _, args)| n == name
                    && (*lib || args.iter().any(|s| s == "IMPORTED" || s == "ALIAS"))),
            "无法修改 gtest 可执行 target：{name}"
        );
    }
    let mut owners = declarations
        .iter()
        .filter(|(_, _, dir, args)| {
            args.iter().skip(1).any(|a| {
                !a.contains('$')
                    && dir.join(a).is_file()
                    && helix_stdx::path::canonicalize(dir.join(a)) == project.source
            })
        })
        .map(|(n, lib, _, _)| (n.clone(), *lib))
        .collect::<std::collections::BTreeSet<_>>();
    for (cmd, args, dir) in &calls {
        if cmd == "target_sources"
            && args.iter().skip(1).any(|a| {
                !a.contains('$')
                    && dir.join(a).is_file()
                    && helix_stdx::path::canonicalize(dir.join(a)) == project.source
            })
        {
            if let Some((name, lib, _, _)) = declarations
                .iter()
                .find(|(n, _, _, _)| Some(n) == args.first())
            {
                owners.insert((name.clone(), *lib));
            }
        }
    }
    let library =
        if let Some(name) = &config.library_target {
            ensure!(
                valid_target(name)
                    && !declarations.iter().any(|(n, lib, _, args)| n == name
                        && (!lib || args.iter().any(|s| s == "IMPORTED"))),
                "无法使用 library-target：{name}"
            );
            Some(name.clone())
        } else {
            ensure!(
                owners.len() <= 1,
                "源文件属于多个 target，请配置 ai-test.library-target"
            );
            if let Some((name, lib)) = owners.iter().next() {
                ensure!(
                    valid_target(name),
                    "动态 target 名称无法可靠解析，请配置 ai-test.library-target"
                );
                ensure!(
                    *lib || test_target.as_ref() == Some(name),
                    "被测代码属于可执行 target {name}；请先提取业务库并设置 library-target"
                );
                lib.then(|| name.clone())
            } else {
                ensure!(
                    test_target.is_some(),
                    "无法可靠确定源文件所属的库；请配置 ai-test.library-target 或 test-target"
                );
                None
            }
        };
    let id_dir = project.test_file.parent().unwrap().to_owned();
    let group = project.root.join("tests/helix-ai");
    let id = id_dir.file_name().unwrap().to_string_lossy().into_owned();
    let test_name = test_target
        .clone()
        .unwrap_or_else(|| project.target_name.clone());
    project.target_name = test_name.clone();
    let mut integration = format!("{MARKER}\nenable_language(CXX)\n# GTest: existing targets -> installed package/vcpkg -> optional download.\n");
    integration.push_str("if(NOT TARGET GTest::gtest_main AND NOT TARGET gtest_main)\n  find_package(GTest CONFIG QUIET)\n  if(NOT GTest_FOUND)\n    find_package(GTest QUIET)\n  endif()\nendif()\n");
    if config.allow_fetch_content {
        integration.push_str("if(NOT TARGET GTest::gtest_main AND NOT TARGET gtest_main)\n  include(FetchContent)\n  if(NOT DEFINED gtest_force_shared_crt)\n    if(DEFINED CMAKE_MSVC_RUNTIME_LIBRARY AND NOT CMAKE_MSVC_RUNTIME_LIBRARY MATCHES \"DLL\")\n      set(gtest_force_shared_crt OFF CACHE BOOL \"\")\n    else()\n      set(gtest_force_shared_crt ON CACHE BOOL \"\")\n    endif()\n  endif()\n  FetchContent_Declare(googletest\n    URL https://github.com/google/googletest/archive/refs/tags/v1.17.0.tar.gz\n    URL_HASH SHA256=65fab701d9829d38cb77c14acdc431d2108bfdbf8979e40eb8ae567edf10b27c\n  )\n  FetchContent_MakeAvailable(googletest)\nendif()\n");
    }
    integration.push_str("if(TARGET GTest::gtest_main)\n  set(_helix_gtest_main GTest::gtest_main)\nelseif(TARGET GTest::Main)\n  set(_helix_gtest_main GTest::Main)\nelseif(TARGET gtest_main)\n  set(_helix_gtest_main gtest_main)\nelse()\n  message(FATAL_ERROR \"GoogleTest not found. Install GTest using vcpkg or enable ai-test.allow-fetch-content.\")\nendif()\n");
    let file = cmake_path(&project.test_file);
    if test_target.is_some() {
        integration.push_str(&format!("target_sources({test_name} PRIVATE \"{file}\")\n"));
        if let Some(library) = &library {
            let links = calls
                .iter()
                .filter(|(c, a, _)| c == "target_link_libraries" && a.first() == Some(&test_name))
                .collect::<Vec<_>>();
            if !links
                .iter()
                .any(|(_, a, _)| a.iter().skip(1).any(|a| a == library))
            {
                let signature = if links.iter().any(|(_, a, _)| {
                    a.get(1)
                        .is_some_and(|a| !["PRIVATE", "PUBLIC", "INTERFACE"].contains(&a.as_str()))
                }) {
                    ""
                } else {
                    "PRIVATE "
                };
                integration.push_str(&format!(
                    "target_link_libraries({test_name} {signature}{library})\n"
                ));
            }
        }
    } else {
        integration.push_str(&format!("add_executable({test_name} \"{file}\")\ntarget_link_libraries({test_name} PRIVATE {} ${{_helix_gtest_main}})\n", library.as_deref().unwrap_or("")));
    }
    integration.push_str(&format!(
        "target_include_directories({test_name} PRIVATE \"{}\" \"{}\" \"{}\")\n",
        cmake_path(&project.root),
        cmake_path(&project.root.join("include")),
        cmake_path(project.source.parent().unwrap())
    ));
    integration.push_str(&format!(
        "target_compile_features({test_name} PRIVATE cxx_std_17)\n"
    ));
    // Generated files are UTF-8. Scope this to the new source, preserving the
    // encoding of handwritten sources when an existing test target is reused.
    integration.push_str(&format!(
        "if(MSVC)\n  set_property(SOURCE \"{file}\" TARGET_DIRECTORY {test_name} APPEND PROPERTY COMPILE_OPTIONS /utf-8)\nendif()\n"
    ));
    // CTest can pass a non-ASCII GoogleTest case name through the Windows
    // ANSI command line and silently run zero cases. Filter the generated
    // suite by its ASCII id and let GoogleTest enumerate its cases itself.
    let suite = &project.test_filter;
    integration.push_str(&format!(
        "if(WIN32)\n  add_test(NAME {suite} COMMAND {test_name} \"--gtest_filter={suite}.*:*/{suite}.*\")\n  set_tests_properties({suite} PROPERTIES FAIL_REGULAR_EXPRESSION \"Running 0 tests from 0 test suites\")\n"
    ));
    if !calls
        .iter()
        .any(|(c, a, _)| c == "gtest_discover_tests" && a.first() == Some(&test_name))
    {
        integration.push_str(&format!(
            "else()\n  include(GoogleTest)\n  gtest_discover_tests({test_name} DISCOVERY_MODE PRE_TEST)\n"
        ));
    }
    integration.push_str("endif()\n");
    change(project, id_dir.join("CMakeLists.txt"), integration)?;
    append(
        project,
        group.join("CMakeLists.txt"),
        &format!("add_subdirectory(\"{id}\")\n"),
        &format!("add_subdirectory(\"{id}\")"),
    )?;
    let original = std::fs::read_to_string(&root_file)?;
    let root_calls = discovery_commands(&original)?;
    let has_ctest = root_calls
        .iter()
        .any(|(c, a)| c == "include" && a.first().is_some_and(|s| s.eq_ignore_ascii_case("CTest")));
    let has_integration = root_calls
        .iter()
        .any(|(c, a)| c == "add_subdirectory" && a.first().is_some_and(|s| s == "tests/helix-ai"));
    if !has_integration {
        let include = if has_ctest { "" } else { "include(CTest)\n" };
        append(project, root_file, &format!("\n# Helix generated unit tests\n{include}if(BUILD_TESTING)\n  add_subdirectory(tests/helix-ai)\nendif()\n"), "# Helix generated unit tests")?;
    }
    project.notes.push(format!(
        "CMake target：{test_name}；GTest 优先复用本机/vcpkg，缺少时{}。",
        if config.allow_fetch_content {
            "允许下载固定版本"
        } else {
            "报告依赖缺失"
        }
    ));
    Ok(())
}

fn valid_target(name: &str) -> bool {
    !name.is_empty()
        && name
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || matches!(c, '_' | '-' | '.' | ':'))
}

fn expand_cmake_path(value: &str, file: &Path, source_dir: &Path, root: &Path) -> String {
    value
        .replace("${CMAKE_CURRENT_SOURCE_DIR}", &source_dir.to_string_lossy())
        .replace(
            "${CMAKE_CURRENT_LIST_DIR}",
            &file.parent().unwrap().to_string_lossy(),
        )
        .replace("${CMAKE_SOURCE_DIR}", &root.to_string_lossy())
        .replace("${PROJECT_SOURCE_DIR}", &root.to_string_lossy())
}

fn collect_cmake(root: &Path, dir: &Path, files: &mut Vec<(PathBuf, PathBuf)>) -> Result<()> {
    let file = dir.join("CMakeLists.txt");
    if file.is_file() {
        collect_cmake_file(root, &file, dir, files)?;
    }
    Ok(())
}

fn collect_cmake_file(
    root: &Path,
    file: &Path,
    source_dir: &Path,
    files: &mut Vec<(PathBuf, PathBuf)>,
) -> Result<()> {
    let file = confined(root, file)?;
    let entry = (file.clone(), source_dir.to_owned());
    if files.contains(&entry) {
        return Ok(());
    }
    ensure!(files.len() < 128, "CMake 文件过多，请缩小项目范围");
    files.push(entry);
    for (cmd, args) in discovery_commands(&snapshot(&file)?.text.context("CMake 文件不存在")?)?
    {
        let Some(name) = args.first() else {
            continue;
        };
        let name = expand_cmake_path(name, &file, source_dir, root);
        if name.contains('$') {
            continue;
        }
        if cmd == "add_subdirectory" && !name.contains("helix-ai") {
            let sub = confined(root, &source_dir.join(name))?;
            ensure!(
                sub != source_dir && !source_dir.starts_with(&sub),
                "CMake 子目录形成循环"
            );
            if sub.is_dir() {
                collect_cmake(root, &sub, files)?;
            }
        } else if cmd == "include" {
            let mut included = source_dir.join(name);
            if included.extension().is_none() {
                included.set_extension("cmake");
            }
            if included.is_file() {
                collect_cmake_file(root, &included, source_dir, files)?;
            }
        }
    }
    Ok(())
}

/// Only infer targets from unconditional/known-enabled code. Explicit target
/// overrides remain available for custom macros and configuration-dependent code.
fn discovery_commands(text: &str) -> Result<Vec<(String, Vec<String>)>> {
    let mut result = Vec::new();
    let mut definitions = 0usize;
    let mut conditions = Vec::new();
    for (cmd, args) in commands(text)? {
        match cmd.as_str() {
            "function" | "macro" => {
                definitions += 1;
                continue;
            }
            "endfunction" | "endmacro" => {
                definitions = definitions.saturating_sub(1);
                continue;
            }
            _ if definitions > 0 => continue,
            "if" => {
                let condition = match args.as_slice() {
                    [v] if ["TRUE", "ON", "1", "BUILD_TESTING"]
                        .contains(&v.to_ascii_uppercase().as_str()) =>
                    {
                        Some(true)
                    }
                    [v] if ["FALSE", "OFF", "0"].contains(&v.to_ascii_uppercase().as_str()) => {
                        Some(false)
                    }
                    [v] if v == "WIN32" => Some(cfg!(windows)),
                    [v] if v == "UNIX" => Some(cfg!(unix)),
                    _ => None,
                };
                conditions.push(condition);
                continue;
            }
            "else" => {
                if let Some(last) = conditions.last_mut() {
                    *last = last.map(|v| !v);
                }
                continue;
            }
            "elseif" => {
                if let Some(last) = conditions.last_mut() {
                    *last = None;
                }
                continue;
            }
            "endif" => {
                conditions.pop();
                continue;
            }
            _ => {}
        }
        if conditions.iter().all(|c| *c == Some(true)) {
            result.push((cmd, args));
        }
    }
    Ok(result)
}

/// Small CMake lexer: respects comments, quoted/bracket arguments and nested ().
/// Variable expansion/custom macros are deliberately not evaluated.
pub(crate) fn commands(text: &str) -> Result<Vec<(String, Vec<String>)>> {
    let bytes = text.as_bytes();
    let mut i = 0;
    let mut tokens = Vec::new();
    while i < bytes.len() {
        if bytes[i].is_ascii_whitespace() {
            i += 1;
            continue;
        }
        if bytes[i] == b'#' {
            i += 1;
            if let Some(end) = bracket_end(text, i)? {
                i = end;
            } else {
                while i < bytes.len() && bytes[i] != b'\n' {
                    i += 1;
                }
            }
            continue;
        }
        if matches!(bytes[i], b'(' | b')') {
            tokens.push(((bytes[i] as char).to_string(), true));
            i += 1;
            continue;
        }
        if bytes[i] == b'"' {
            i += 1;
            let mut value = Vec::new();
            while i < bytes.len() && bytes[i] != b'"' {
                if bytes[i] == b'\\' && i + 1 < bytes.len() {
                    i += 1;
                }
                value.push(bytes[i]);
                i += 1;
            }
            ensure!(i < bytes.len(), "CMake 引号未闭合");
            i += 1;
            tokens.push((String::from_utf8(value)?, false));
            continue;
        }
        if let Some(end) = bracket_end(text, i)? {
            tokens.push((text[i..end].to_owned(), false));
            i = end;
            continue;
        }
        let start = i;
        while i < bytes.len()
            && !bytes[i].is_ascii_whitespace()
            && !matches!(bytes[i], b'(' | b')' | b'#')
        {
            i += 1;
        }
        tokens.push((text[start..i].to_owned(), false));
    }
    let mut result = Vec::new();
    let mut i = 0;
    while i + 1 < tokens.len() {
        let name = tokens[i].0.to_ascii_lowercase();
        ensure!(
            tokens[i + 1] == ("(".to_owned(), true),
            "无法解析 CMake 指令 {name}"
        );
        i += 2;
        let mut depth = 1;
        let mut args = Vec::new();
        while i < tokens.len() && depth > 0 {
            if tokens[i].1 {
                match tokens[i].0.as_str() {
                    "(" => depth += 1,
                    ")" => depth -= 1,
                    _ => {}
                }
            }
            if depth > 0 {
                args.push(tokens[i].0.clone());
            }
            i += 1;
        }
        ensure!(depth == 0, "CMake 括号未闭合");
        result.push((name, args));
    }
    Ok(result)
}

fn bracket_end(text: &str, start: usize) -> Result<Option<usize>> {
    let b = text.as_bytes();
    if b.get(start) != Some(&b'[') {
        return Ok(None);
    }
    let mut j = start + 1;
    while b.get(j) == Some(&b'=') {
        j += 1;
    }
    if b.get(j) != Some(&b'[') {
        return Ok(None);
    }
    let close = format!("]{}]", "=".repeat(j - start - 1));
    let offset = text[j + 1..]
        .find(&close)
        .context("CMake bracket 参数未闭合")?;
    Ok(Some(j + 1 + offset + close.len()))
}

pub(crate) fn changes(project: &Project, code: &str) -> Result<Vec<FileChange>> {
    let before = project
        .snapshots
        .iter()
        .find(|s| s.path == project.test_file)
        .context("缺少测试文件快照")?
        .clone();
    let marker = if project.language == "python" {
        MARKER
    } else {
        C_MARKER
    };
    let mut changes = vec![FileChange {
        before,
        after: format!("{marker}\n{}\n", code.trim()),
    }];
    changes.extend(project.build_changes.clone());
    Ok(changes)
}


use super::*;
use std::{collections::BTreeSet, fs, path::Path, process::Command};

#[test]
fn detects_only_root_markers_and_combines_evidence() -> anyhow::Result<()> {
    let root = tempfile::tempdir()?;
    fs::create_dir(root.path().join(".git"))?;
    fs::create_dir_all(root.path().join("apps/web"))?;
    fs::write(root.path().join("apps/web/package.json"), "{}")?;
    fs::write(root.path().join("Cargo.toml"), "")?;
    fs::write(root.path().join("pyproject.toml"), "")?;
    fs::write(root.path().join("requirements.txt"), "")?;
    let project = detect(&root.path().join("apps/web"))?;
    assert_eq!(
        project.target,
        root.path().canonicalize()?.join(".gitignore")
    );
    assert!(project.is_git);
    assert_eq!(project.detected.len(), 2);
    assert_eq!(
        project.detected["python"],
        ["pyproject.toml", "requirements.txt"]
    );
    assert!(!project.detected.contains_key("node"));
    assert!(project.warnings.is_empty());
    Ok(())
}

#[test]
fn prefers_nearest_git_marker_over_helix_and_handles_worktrees() -> anyhow::Result<()> {
    let outer = tempfile::tempdir()?;
    fs::create_dir(outer.path().join(".git"))?;
    let inner = outer.path().join("nested");
    fs::create_dir_all(inner.join("src/.helix"))?;
    assert_eq!(
        detect(&inner.join("src"))?.target,
        outer.path().canonicalize()?.join(".gitignore")
    );
    fs::write(inner.join(".git"), "gitdir: unused-path")?;
    assert_eq!(
        detect(&inner.join("src"))?.target,
        inner.canonicalize()?.join(".gitignore")
    );
    Ok(())
}

#[test]
fn supports_non_git_projects_and_all_marker_groups() -> anyhow::Result<()> {
    let root = tempfile::tempdir()?;
    fs::create_dir(root.path().join(".helix"))?;
    fs::create_dir(root.path().join("src"))?;
    for marker in [
        "package.json",
        "go.mod",
        "pom.xml",
        "build.gradle.kts",
        "CMakeLists.txt",
        "sample.csproj",
    ] {
        fs::write(root.path().join(marker), "")?;
    }
    let project = detect(&root.path().join("src"))?;
    assert!(!project.is_git);
    for id in [
        "node", "go", "java", "maven", "gradle", "cpp", "cmake", "dotnet",
    ] {
        assert!(project.detected.contains_key(id), "missing {id}");
    }
    assert_eq!(project.detected["java"].len(), 2);
    Ok(())
}

#[test]
fn cap_does_not_hide_fixed_markers_or_report_complete_detection() -> anyhow::Result<()> {
    let root = tempfile::tempdir()?;
    for n in 0..4097 {
        fs::write(root.path().join(format!("item{n}")), "")?;
    }
    fs::write(root.path().join("Cargo.toml"), "")?;
    let project = detect(root.path())?;
    assert!(project.detected.contains_key("rust"));
    assert!(!project.warnings.is_empty());
    Ok(())
}

#[cfg(unix)]
#[test]
fn ignores_symlink_markers_and_directory_extensions() -> anyhow::Result<()> {
    let root = tempfile::tempdir()?;
    fs::write(root.path().join("other"), "")?;
    std::os::unix::fs::symlink("other", root.path().join("Cargo.toml"))?;
    fs::create_dir(root.path().join("directory.csproj"))?;
    assert!(detect(root.path())?.detected.is_empty());
    Ok(())
}

#[test]
fn composition_is_ordered_and_preserves_exception_blocks() -> anyhow::Result<()> {
    let ids = BTreeSet::from(["dotenv", "rust", "macos"]);
    let text = generate(&ids)?;
    assert!(text.starts_with("# Generated by Helix; templates: rust, macos, dotenv\n"));
    assert!(text.find("# --- Rust ---").unwrap() < text.find("# --- macOS ---").unwrap());
    assert!(text.find(".env.*\n").unwrap() < text.find("!.env.example\n").unwrap());
    assert!(text.ends_with('\n') && !text.ends_with("\n\n"));
    assert!(!text.contains('\r'));
    assert!(generate(&BTreeSet::new()).is_err());
    assert!(generate(&BTreeSet::from(["unknown"])).is_err());
    assert_eq!(TEMPLATES.len(), 19);
    assert_eq!(
        TEMPLATES
            .iter()
            .map(|t| t.id)
            .collect::<BTreeSet<_>>()
            .len(),
        TEMPLATES.len()
    );
    Ok(())
}

fn ignored(root: &Path, file: &str) -> bool {
    Command::new("git")
        .args([
            "-c",
            "core.excludesFile=",
            "check-ignore",
            "--no-index",
            "--quiet",
            "--",
            file,
        ])
        .current_dir(root)
        .status()
        .unwrap()
        .success()
}

#[test]
fn templates_ignore_outputs_but_preserve_source_lockfiles_and_examples() -> anyhow::Result<()> {
    let root = tempfile::tempdir()?;
    assert!(Command::new("git")
        .args(["init", "--quiet"])
        .current_dir(root.path())
        .status()?
        .success());
    let ids = BTreeSet::from([
        "rust", "node", "python", "go", "java", "cpp", "dotnet", "maven", "gradle", "cmake",
        "dotenv",
    ]);
    fs::write(root.path().join(".gitignore"), generate(&ids)?)?;
    for file in [
        "target/debug/hx",
        "node_modules/pkg/index.js",
        "__pycache__/main.pyc",
        ".venv/bin/python",
        "build/CMakeCache.txt",
        "obj/Debug/cache",
        ".env",
        ".env.local",
    ] {
        assert!(ignored(root.path(), file), "should ignore {file}");
    }
    for file in [
        "Cargo.lock",
        "package-lock.json",
        "pnpm-lock.yaml",
        "yarn.lock",
        "poetry.lock",
        "Pipfile.lock",
        "uv.lock",
        "go.sum",
        "src/build/main.cpp",
        "src/main.rs",
        ".env.example",
        ".env.sample",
        ".env.template",
        "gradle/wrapper/gradle-wrapper.jar",
    ] {
        assert!(!ignored(root.path(), file), "should preserve {file}");
    }
    Ok(())
}

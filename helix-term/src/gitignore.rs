mod catalog;
mod detect;

pub(crate) use catalog::{Template, TEMPLATES};
pub(crate) use detect::{detect, Project};

use std::collections::BTreeSet;

/// Preserve entire ordered blocks: sorting or deduplicating rules changes negation semantics.
pub(crate) fn generate(ids: &BTreeSet<&str>) -> anyhow::Result<String> {
    anyhow::ensure!(!ids.is_empty(), "Select at least one template");
    for id in ids {
        anyhow::ensure!(
            TEMPLATES.iter().any(|t| t.id == *id),
            "Unknown template: {id}"
        );
    }
    let chosen: Vec<_> = TEMPLATES.iter().filter(|t| ids.contains(t.id)).collect();
    let mut text = format!(
        "# Generated by Helix; templates: {}\n",
        chosen.iter().map(|t| t.id).collect::<Vec<_>>().join(", ")
    );
    for template in chosen {
        anyhow::ensure!(
            !template.text.trim().is_empty(),
            "Empty template: {}",
            template.id
        );
        text.push_str(&format!("\n# --- {} ---\n", template.name));
        text.push_str(template.text.trim_end_matches(['\r', '\n']));
        text.push('\n');
    }
    Ok(text)
}

